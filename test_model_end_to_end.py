"""End-to-end mechanics test on SYNTHETIC data only (not MLB evidence)."""
import numpy as np, pandas as pd, pytest
from wsr import flight, model, geometry, aggregate

def _setup(tmp_path, monkeypatch, status="VERIFIED"):
    proc, ref = tmp_path / "processed", tmp_path / "reference"
    proc.mkdir(); ref.mkdir()
    for mod in (model, aggregate):
        monkeypatch.setattr(mod, "PROCESSED", proc)
    monkeypatch.setattr(model, "REFERENCE", ref)
    # 30 synthetic parks: walls 330..388 ft, 8 ft high
    rows = []
    for i in range(30):
        d = 330 + 2*i
        rows.append(dict(park_id=f"P{i:02d}", club="X", venue_name="Synthetic", season_start=2025, season_end=2025,
                         lf_line_ft=d-10, lcf_ft=d+15, cf_ft=d+30, rcf_ft=d+15, rf_line_ft=d-10,
                         wall_ht_lf_ft=8, wall_ht_lcf_ft=8, wall_ht_cf_ft=8, wall_ht_rcf_ft=8, wall_ht_rf_ft=8,
                         source_url="https://example.org/synthetic", status=status))
    geometry.build_profiles(pd.DataFrame(rows)).to_csv(ref / "park_wall_profiles.csv", index=False)
    pd.DataFrame([dict(season=2025, team_id=f"T{i}", club="X", park_id=f"P{i:02d}", venue_name="S",
                       mapping_status="VERIFIED") for i in range(30)]).to_csv(ref / "team_park_seasons.csv", index=False)
    # HRs generated by the model itself with known spin -> distance
    ev = np.array([108, 100, 98, 104, 92.0]); la = np.array([30, 27, 26, 28, 33.0])
    d = flight.landing_distance_ft(ev, la, np.full(5, 2200.0))
    hrs = pd.DataFrame({"hr_record_id": [f"H{i}" for i in range(5)], "season": 2025, "batter_id": 1,
                        "player_name": "Synth", "batting_team": "T0", "exit_velocity_mph": ev,
                        "launch_angle_deg": la, "tracked_distance_ft": d, "hit_coord_x": 125.42, "hit_coord_y": 80.0})
    hrs.to_csv(proc / "home_runs.csv", index=False)
    return proc, d

def test_pipeline_classifies_and_orders(tmp_path, monkeypatch):
    proc, d = _setup(tmp_path, monkeypatch)
    out, sims = model.run_model()
    out = out.set_index("hr_record_id")
    assert (out.model_status == "MODELED").all()
    assert sims.groupby("hr_record_id").park_id.nunique().eq(30).all()
    # farther ball clears at least as many parks
    order = np.argsort(d)
    ks = out.parks_cleared.to_numpy()[order]
    assert (np.diff(ks) >= 0).all()
    assert out.wsr_classification.isin(["WALL_SCRAPER", "STANDARD", "NO_DOUBTER"]).all()
    assert (proc / "player_season_wsr.csv").exists()

def test_unverified_geometry_stays_unmodeled(tmp_path, monkeypatch):
    _setup(tmp_path, monkeypatch, status="PROVISIONAL")
    out, sims = model.run_model()
    assert (out.wsr_classification == "UNMODELED").all()
    assert out.model_status.str.startswith("UNMODELED_PARK_GEOMETRY").all()

def test_provisional_goes_to_separate_folder(tmp_path, monkeypatch):
    proc, _ = _setup(tmp_path, monkeypatch, status="PROVISIONAL")
    out, _ = model.run_model(allow_provisional=True)
    assert (proc / "provisional" / "home_runs.csv").exists()
    assert out.model_status.str.contains("PROVISIONAL").all()

def test_spray_angle_signs():
    assert abs(flight.spray_angle_deg(125.42, 100)) < 1e-9
    assert flight.spray_angle_deg(60, 120) < 0 < flight.spray_angle_deg(190, 120)

def test_sensitivity_and_figures(tmp_path, monkeypatch):
    from wsr import sensitivity, figures
    proc, _ = _setup(tmp_path, monkeypatch)
    monkeypatch.setattr(sensitivity, "PROCESSED", proc); monkeypatch.setattr(figures, "PROCESSED", proc)
    monkeypatch.setattr(figures, "ROOT", tmp_path)
    model.run_model()
    s = sensitivity.run_sensitivity(n_sample=5, draws=3)
    assert 0 <= s["mean_class_stability"] <= 1
    assert "park_clearance_rates.png" in figures.make_figures()
